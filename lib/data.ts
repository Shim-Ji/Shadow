/** 시간 → "m:ss" */
export function fmt(t: number): string {
  const s = Math.max(0, Math.floor(t));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

export const ALL_LYRICS: (Lyric & { sceneId: string })[] = SCENES.flatMap((sc) =>
  sc.lyrics.map((l) => ({ ...l, sceneId: sc.id })),
);

/** t 시점에 불리는(또는 직전에 불린) 가사 */
export function lyricAt(t: number): Lyric | undefined {
  let found: Lyric | undefined;
  for (const l of ALL_LYRICS) {
    if (l.s - 1 <= t) found = l;
    else break;
  }
  if (found && t - found.e > 4) return undefined;
  return found;
}

export function sceneAt(t: number): Scene | undefined {
  return SCENES.find((s) => t >= s.start && t < s.end);
}

const CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ";
/** 초성 힌트: 한글은 초성만 남깁니다 */
export function initials(text: string): string {
  return [...text]
    .map((ch) => {
      const c = ch.charCodeAt(0) - 0xac00;
      if (c < 0 || c > 11171) return ch;
      return CHO[Math.floor(c / 588)];
    })
    .join("");
}
